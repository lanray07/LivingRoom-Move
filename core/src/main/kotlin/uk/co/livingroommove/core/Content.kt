package uk.co.livingroommove.core

import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import java.time.Instant

val catalogueJson = Json { ignoreUnknownKeys = false; encodeDefaults = true }

@Serializable enum class ReviewStatus { DRAFT, IN_REVIEW, APPROVED }
@Serializable enum class Posture { SEATED, STANDING, MIXED }
@Serializable data class Review(val status: ReviewStatus = ReviewStatus.DRAFT, val date: String? = null,
    val reviewer: String? = null, val credentials: String? = null, val evidenceId: String? = null)
@Serializable data class Licence(val reference: String = "", val offlineAllowed: Boolean = false,
    val expiresAt: String? = null)
@Serializable data class VoiceAsset(val language: String, val audioUri: String? = null,
    val captionsUri: String? = null, val script: String = "", val humanRecorded: Boolean = false,
    val approved: Boolean = false, val licenceReference: String = "")
@Serializable data class Movement(val id: String, val title: String, val durationSeconds: Int,
    val narration: String, val seatedAlternativeId: String? = null)
@Serializable data class Workout(val id: String, val title: String, val description: String,
    val durationMinutes: Int, val difficulty: String, val posture: Posture,
    val category: String, val language: String = "en-GB", val programmeId: String? = null,
    val review: Review = Review(), val contraindicationNotes: List<String> = emptyList(),
    val safetyPrompts: List<String> = emptyList(), val movements: List<Movement> = emptyList(),
    val videoUri: String? = null, val voices: List<VoiceAsset> = emptyList(),
    val licence: Licence = Licence(), val placeholder: Boolean = true)
@Serializable data class Programme(val id: String, val title: String, val weeks: Int = 4,
    val description: String, val workoutIds: List<String>, val placeholder: Boolean = true)
@Serializable data class Catalogue(val schemaVersion: Int, val version: Long, val expiresAt: String? = null,
    val workouts: List<Workout>, val programmes: List<Programme>) {
    fun validate() {
        require(schemaVersion == 1 && version > 0)
        require(workouts.map { it.id }.distinct().size == workouts.size)
        require(programmes.map { it.id }.distinct().size == programmes.size)
        workouts.forEach {
            require(it.id.matches(Regex("[a-z0-9-]+")))
            require(it.durationMinutes in listOf(5, 10, 15))
            require(it.programmeId == null || programmes.any { p -> p.id == it.programmeId })
            require(it.videoUri == null || safeMediaUri(it.videoUri))
            it.voices.forEach { v ->
                require(v.audioUri == null || safeMediaUri(v.audioUri))
                require(v.captionsUri == null || safeMediaUri(v.captionsUri))
            }
        }
        programmes.forEach { p -> require(p.workoutIds.all { id -> workouts.any { it.id == id } }) }
    }
}

fun safeMediaUri(uri: String): Boolean = uri.startsWith("https://") ||
    (uri.startsWith("asset:///") && !uri.contains(".."))

fun approvedVoice(workout: Workout): VoiceAsset? = workout.voices.firstOrNull {
    it.language == workout.language && it.approved && it.humanRecorded && it.licenceReference.isNotBlank() &&
        it.audioUri?.let(::safeMediaUri) == true && it.captionsUri?.let(::safeMediaUri) == true
}

/** Every field is backed by external review/licensing records, never generated by the app. */
object PublicationGate {
    fun reason(workout: Workout, now: Instant = Instant.now()): String? = when {
        workout.placeholder || workout.review.status != ReviewStatus.APPROVED -> "professional_review_required"
        listOf(workout.review.date, workout.review.reviewer, workout.review.credentials, workout.review.evidenceId)
            .any { it.isNullOrBlank() } -> "review_evidence_missing"
        runCatching { java.time.LocalDate.parse(workout.review.date) }.getOrNull() == null -> "review_date_invalid"
        workout.movements.isEmpty() || workout.safetyPrompts.isEmpty() -> "content_incomplete"
        workout.videoUri.isNullOrBlank() || !safeMediaUri(workout.videoUri) -> "video_unavailable"
        workout.licence.reference.isBlank() -> "licence_required"
        expired(workout.licence.expiresAt, now) -> "licence_expired"
        approvedVoice(workout) == null -> "approved_voice_required"
        else -> null
    }
    private fun expired(value: String?, now: Instant) = value != null &&
        runCatching { !Instant.parse(value).isAfter(now) }.getOrDefault(true)
}

@Serializable data class Preferences(val posture: String = "ALL", val duration: Int = 0,
    val textScale: Float = 1f, val narrationSpeed: Float = 1f, val captions: Boolean = true,
    val reducedMotion: Boolean = true, val reminder: Boolean = false, val language: String = "en-GB")
@Serializable data class SessionProgress(val positionMs: Long = 0, val completed: Int = 0,
    val lastPlayedAt: Long = 0)
@Serializable data class LocalState(val preferences: Preferences = Preferences(),
    val safetyVersion: Int = 0, val favourites: Set<String> = emptySet(),
    val progress: Map<String, SessionProgress> = emptyMap())

fun recordCompletion(state: LocalState, workout: Workout, endedNaturally: Boolean, now: Long): LocalState {
    require(endedNaturally && PublicationGate.reason(workout) == null)
    val previous = state.progress[workout.id] ?: SessionProgress()
    return state.copy(progress = state.progress + (workout.id to previous.copy(positionMs = 0,
        completed = previous.completed + 1, lastPlayedAt = now)))
}

data class Offer(val sku: String, val title: String, val localisedPrice: String)
data class Entitlement(val active: Boolean, val expiresAt: Instant?, val verified: Boolean) {
    fun permits(now: Instant) = verified && active && expiresAt?.isAfter(now) == true
}
